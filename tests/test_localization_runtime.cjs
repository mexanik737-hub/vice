const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');

const html = fs.readFileSync(new URL('../android/app/src/main/assets/game/index.html', `file://${__filename}`), 'utf8');
const match = html.match(/<script id="viceburg-ru-layer">([\s\S]*?)<\/script>/);
assert.ok(match, 'built HTML contains the Russian runtime layer');
const code = match[1].replace(/\/\/ Never traverse the embedded Twine source[\s\S]*$/, 'globalThis.vbTranslate = translated;})();');
const context = {};
vm.runInNewContext(code, context);
assert.equal(context.vbTranslate('Options'), 'Настройки');
assert.equal(context.vbTranslate('You agreed to start dating Alice.'), 'Вы начали встречаться с Alice.');
assert.equal(context.vbTranslate('A note. Open Quests in the sidebar - each active quest lists its tasks, and the unticked one is what to do next. More text.'), 'A note. Откройте «Задания» на боковой панели: в каждом активном задании есть список целей. Следующая цель отмечена пустым флажком. More text.');
assert.equal(context.vbTranslate('Could not save preset: disk full'), 'Не удалось сохранить шаблон: disk full');
const genderLabel = { closest: selector => selector === '#gender-selector .option-label' };
assert.equal(context.vbTranslate('Male', genderLabel), 'Мужчина');
assert.equal(context.vbTranslate('Male'), null);
const skinLabel = { closest: selector => selector === '#skin-selector .option-label' };
assert.equal(context.vbTranslate('Black', skinLabel), 'Тёмная');
const voyageLabel = { closest: selector => selector === '.sidebar-voyage' };
assert.equal(context.vbTranslate('⚓ Voyage · Day', voyageLabel), '⚓ Плавание · День');
assert.equal(context.vbTranslate('left', voyageLabel), 'осталось');
const debtLabel = { closest: selector => selector === '.sidebar-note--quest' };
assert.equal(context.vbTranslate('Days Left to Collect:', debtLabel), 'Дней до взыскания:');
const faqIntro = { closest: selector => selector === '.faq-intro' || selector === '.faq-intro li' };
assert.equal(context.vbTranslate('Open', faqIntro), 'Откройте');
assert.equal(context.vbTranslate('in the sidebar - each active quest lists its tasks, and the unticked one is what to do next.', faqIntro), 'на боковой панели: в каждом активном задании перечислены задачи, а невыполненная подскажет, что делать дальше.');
assert.equal(context.vbTranslate('Basics', faqIntro), 'Основы');
assert.equal(context.vbTranslate('an unmapped sentence'), null);
console.log('Localization exact phrases, FAQ/context rules, and dynamic templates: OK');
